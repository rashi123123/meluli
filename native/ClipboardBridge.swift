import AppKit
import Foundation
import Darwin

enum BridgeError: Error { case invalidRequest, changed, tooLarge, unavailable }

func beginTransaction(_ board: NSPasteboard, text: String) throws -> () -> Bool {
    let before = board.changeCount
    var saved: [NSPasteboardItem] = []
    var bytes = 0
    for item in board.pasteboardItems ?? [] {
        let copy = NSPasteboardItem()
        for type in item.types {
            guard let data = item.data(forType: type) else { throw BridgeError.unavailable }
            bytes += data.count
            guard bytes <= 32 * 1024 * 1024 else { throw BridgeError.tooLarge }
            guard copy.setData(data, forType: type) else { throw BridgeError.unavailable }
        }
        saved.append(copy)
    }
    guard board.changeCount == before else { throw BridgeError.changed }
    // Stays on this Mac: Universal Clipboard must not carry a paste to other devices.
    board.prepareForNewContents(with: .currentHostOnly)
    guard board.setString(text, forType: .string) else {
        if !saved.isEmpty { board.writeObjects(saved) }
        throw BridgeError.unavailable
    }
    // nspasteboard.org markers: clipboard managers skip what exists only to carry a paste.
    for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
        board.setData(Data(), forType: .init(marker))
    }
    let written = board.changeCount
    return {
        // A new copy, including identical text, belongs to the user and is left intact.
        guard board.changeCount == written else { return false }
        board.clearContents()
        if !saved.isEmpty { return board.writeObjects(saved) }
        return true
    }
}

func selfTest() throws {
    let board = NSPasteboard(name: .init("MeluliTest-\(UUID().uuidString)"))
    defer { board.releaseGlobally() }
    let item = NSPasteboardItem()
    let custom = NSPasteboard.PasteboardType("org.meluli.test")
    item.setString("before", forType: .string)
    item.setData(Data("<b>before</b>".utf8), forType: .html)
    item.setData(Data([0, 1, 2, 255]), forType: custom)
    board.clearContents(); board.writeObjects([item])
    let restore = try beginTransaction(board, text: "dictation")
    precondition(board.string(forType: .string) == "dictation")
    precondition(board.data(forType: .init("org.nspasteboard.TransientType")) != nil)
    precondition(restore())
    precondition(board.data(forType: .init("org.nspasteboard.TransientType")) == nil)
    precondition(board.string(forType: .string) == "before")
    precondition(board.data(forType: .html) == Data("<b>before</b>".utf8))
    precondition(board.data(forType: custom) == Data([0, 1, 2, 255]))
    let preserveNewCopy = try beginTransaction(board, text: "same")
    board.clearContents(); board.setString("same", forType: .string)
    precondition(!preserveNewCopy())
    precondition(board.string(forType: .string) == "same")
    board.clearContents()
    let restoreEmpty = try beginTransaction(board, text: "temporary")
    precondition(restoreEmpty())
    precondition((board.pasteboardItems ?? []).isEmpty)
    print("{\"selfTest\":\"passed\",\"checks\":3,\"usesGeneralClipboard\":false}")
}

do {
    if CommandLine.arguments.dropFirst() == ["--self-test"] {
        try selfTest()
    } else {
        guard let line = readLine(), line.utf8.count <= 1_000_000,
              let object = try JSONSerialization.jsonObject(with: Data(line.utf8)) as? [String: String],
              let text = object["text"], !text.isEmpty else { throw BridgeError.invalidRequest }
        let restore = try beginTransaction(.general, text: text)
        print("{\"ready\":true}"); fflush(stdout)
        // Parent closes stdin after paste consumption. EOF/crash also restores the board.
        // A bounded timeout ensures an orphan helper cannot hold clipboard contents forever.
        var input = pollfd(fd: STDIN_FILENO, events: Int16(POLLIN | POLLHUP), revents: 0)
        _ = poll(&input, 1, 8_000)
        let restored = restore()
        print("{\"restored\":\(restored)}")
    }
} catch {
    // Do not print requests, clipboard contents, or arbitrary native error descriptions.
    print("{\"error\":\"clipboard_unavailable\"}")
    exit(1)
}
